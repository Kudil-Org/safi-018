#!/usr/bin/env node
// Generates the local secrets required by the AWS-only overlay.
//
//   node deploy/aws/gen-supabase-keys.mjs
//
// Print the output once, paste it into the repo-root .env, and keep it out of
// git. Re-running generates new keys; existing Postgres volumes keep the old
// postgres password, so rotating that requires a database password change too.
import crypto from "node:crypto";

const b64url = (value) => Buffer.from(value).toString("base64url");

function sign(payload, secret) {
  const header = b64url(JSON.stringify({ alg: "HS256", typ: "JWT" }));
  const body = b64url(JSON.stringify(payload));
  const signature = crypto.createHmac("sha256", secret).update(`${header}.${body}`).digest("base64url");
  return `${header}.${body}.${signature}`;
}

const jwtSecret = process.env.SUPABASE_JWT_SECRET || crypto.randomBytes(48).toString("hex");
const now = Math.floor(Date.now() / 1000);
const exp = now + 10 * 365 * 24 * 60 * 60;
const claims = { iss: "safi-self-hosted", ref: "safi", iat: now, exp };

const anonKey = sign({ ...claims, role: "anon" }, jwtSecret);
const serviceRoleKey = sign({ ...claims, role: "service_role" }, jwtSecret);

const lines = [
  "# Generated by deploy/aws/gen-supabase-keys.mjs. Never commit these values.",
  `POSTGRES_PASSWORD=${crypto.randomBytes(24).toString("hex")}`,
  `AUTHENTICATOR_PASSWORD=${crypto.randomBytes(24).toString("hex")}`,
  `SUPABASE_JWT_SECRET=${jwtSecret}`,
  `SUPABASE_ANON_KEY=${anonKey}`,
  `SUPABASE_SERVICE_ROLE_KEY=${serviceRoleKey}`,
  `LITELLM_MASTER_KEY=sk-${crypto.randomBytes(24).toString("hex")}`
];

console.log(lines.join("\n"));
